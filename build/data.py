def district_reviews(metro, dist_slug, dist_ko, dongs):
    out = []
    for i in range(6):
        s = _seed("rev", metro, dist_slug, i)
        name = _R_NAMES[s % len(_R_NAMES)]
        course = _R_COURSES[(s // 7) % len(_R_COURSES)]
        sit = _R_SITUATIONS[(s // 13) % len(_R_SITUATIONS)]
        dong = dongs[(s // 17) % len(dongs)]
        out.append({
            "name": name, "course": course, "dong": dong,
            "text": f"{dist_ko} {dong}에서 받았어요. {sit}",
            "stars": 5 if s % 5 else 4,
        })
    return out
