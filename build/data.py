def _seed(*parts):
    h = hashlib.md5("|".join(str(p) for p in parts).encode("utf-8")).hexdigest()
    return int(h, 16)

def arrival_minutes(metro, dist_slug, dong):
    base = {"seoul": 30, "gyeonggi": 38, "incheon": 36, "busan": 35}.get(metro, 34)
    spread = _seed(metro, dist_slug, dong) % 13  # 0~12
    return base + spread

def district_rating(metro, dist_slug):
    return round(4.85 + (_seed("rate", metro, dist_slug) % 13) / 100, 2)  # 4.85~4.97

def district_review_count(metro, dist_slug):
    return 60 + _seed("rc", metro, dist_slug) % 180  # 60~239

